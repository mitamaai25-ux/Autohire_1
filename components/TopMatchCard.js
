import React from 'react';
import { View, Text, TouchableOpacity, StyleSheet } from 'react-native';

export default function TopMatchCard({ item, onPress }) {
  return (
    <TouchableOpacity onPress={onPress} style={styles.card}>
      <View style={styles.avatar}>{/* rounded avatar placeholder */}<Text style={{fontSize:18}}>{item.name[0]}</Text></View>
      <Text style={styles.name}>{item.name}</Text>
      <Text style={styles.role}>{item.role}</Text>

      <View style={{flexDirection:'row', marginTop:8}}>
        <Text style={{marginRight:8}}>⭐ {item.rating}</Text>
        <Text>${item.rate}/hr</Text>
      </View>

      <View style={{flexDirection:'row', marginTop:10, flexWrap:'wrap'}}>
        {item.tags.map(t => <View key={t} style={styles.tag}><Text style={{fontSize:12}}>{t}</Text></View>)}
      </View>
    </TouchableOpacity>
  );
}

const styles = StyleSheet.create({
  card:{width:180, backgroundColor:'#fff', borderRadius:12, padding:12, marginRight:12, elevation:2},
  avatar:{width:72,height:72,borderRadius:12, backgroundColor:'#f0f3ff', alignItems:'center', justifyContent:'center'},
  name:{fontWeight:'700', marginTop:8},
  role:{color:'#6b7280'},
  tag:{paddingHorizontal:8, paddingVertical:6, backgroundColor:'#eef6ff', borderRadius:8, marginRight:6, marginBottom:6}
});
